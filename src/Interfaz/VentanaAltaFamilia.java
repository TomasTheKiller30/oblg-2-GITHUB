    private void btnAceptarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAceptarActionPerformed
        String cedula = txtCedula.getText().trim();
        String apellido = txtApellido.getText().trim();
        String celular = txtCelular.getText().trim();
        if (cedula.isEmpty() || apellido.isEmpty() || celular.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Debe completar todos los campos.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        } else if (modelo.existeFamilia(cedula)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Ya existe una familia con la cédula " + cedula + ".", "Advertencia", javax.swing.JOptionPane.WARNING_MESSAGE);
        } else {
            modelo.registrarFamilia(cedula, apellido, celular);
            javax.swing.JOptionPane.showMessageDialog(this, "Se registró la familia " + apellido + ".", "Registro exitoso", javax.swing.JOptionPane.INFORMATION_MESSAGE);
            txtCedula.setText("");
            txtApellido.setText("");
            txtCelular.setText("");
            txtCedula.requestFocus();
        }
    }//GEN-LAST:event_btnAceptarActionPerformed


