    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        Empresa empresa = (Empresa) listaEmpresas.getSelectedValue();
        int tipo = comboTipo.getSelectedIndex() + 1;
        int kilos = modelo.convertirEntero(txtKilos.getText());

        if (empresa == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Debe seleccionar una empresa.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        } else if (kilos <= 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "La cantidad debe ser un número entero mayor a cero.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        } else {
            int numero = modelo.registrarDonacion(empresa, tipo, kilos);
            javax.swing.JOptionPane.showMessageDialog(this, "Se registró la donación Nº " + numero + ".", "Registro exitoso", javax.swing.JOptionPane.INFORMATION_MESSAGE);
            txtKilos.setText("");
            cargarDatos();
        }
    }//GEN-LAST:event_btnRegistrarActionPerformed





