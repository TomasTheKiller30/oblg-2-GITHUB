    private void listaAdopcionesValueChanged(javax.swing.event.ListSelectionEvent evt) {//GEN-FIRST:event_listaAdopcionesValueChanged
        Adopcion a = listaAdopciones.getSelectedValue();
        
        if (a != null){
            labelMostApellido.setText(a.getFamilia().getApellido());
            labelMostCedula.setText(String.valueOf(a.getFamilia().getCedula()));
            labelMostCelular.setText(String.valueOf(a.getFamilia().getCelular()));
        
            labelMostNombre.setText(a.getAnimal().getNombreAnimal());
            labelMostCodigo.setText(a.getAnimal().getCodigo());
            labelMostTemperamento.setText(a.getAnimal().getTemperamento());
            labelMostPeso.setText(String.valueOf(a.getAnimal().getPeso()));
        }
        else {
            labelMostApellido.setText("---");
            labelMostCedula.setText("---");
            labelMostCelular.setText("---");
            labelMostNombre.setText("---");
            labelMostCodigo.setText("---");
            labelMostTemperamento.setText("---");
            labelMostPeso.setText("---");
        }
    }//GEN-LAST:event_listaAdopcionesValueChanged

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        Adopcion a = listaAdopciones.getSelectedValue();
        
        if (a == null) {
            JOptionPane.showMessageDialog(this, "No se ha elegido una animal", "Advertencia", JOptionPane.WARNING_MESSAGE);
        } else {
            modelo.anularAdopcion(a); // está en Dominio -> Metodos de Adopcion
            cargarListas();
        }
    }//GEN-LAST:event_jButton1ActionPerformed
    
    public void cargarListas(){
        listaAdopciones.setListData(modelo.adopcionesDisponibles());
    }

