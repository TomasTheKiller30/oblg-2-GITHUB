    private void btnAceptarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAceptarActionPerformed
        String nombre = txtNombre.getText().trim();
        String rut = txtRut.getText().trim();
        String direccion = txtDireccion.getText().trim();
        if (nombre.isEmpty() || rut.isEmpty() || direccion.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Debe completar todos los campos.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        } else if (modelo.existeEmpresa(rut)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Ya existe una empresa con el rut " + rut + ".", "Advertencia", javax.swing.JOptionPane.WARNING_MESSAGE);
        } else {
            modelo.registrarEmpresa(nombre, rut, direccion);
            javax.swing.JOptionPane.showMessageDialog(this, "Se registró la empresa " + nombre + ".", "Registro exitoso", javax.swing.JOptionPane.INFORMATION_MESSAGE);
            txtNombre.setText("");
            txtRut.setText("");
            txtDireccion.setText("");
            txtNombre.requestFocus();
        }
    }//GEN-LAST:event_btnAceptarActionPerformed

